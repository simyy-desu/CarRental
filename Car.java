public class Car {
    public String name;
    public String type;
    public String detail;
    public String category;
    public String plateNum;
    public String imagePath;

    public Car(String name, String type, String detail, String category, String plateNum, String imagePath) {
        this.name = name;
        this.type = type;
        this.detail = detail;
        this.category = category;
        this.plateNum = plateNum;
        this.imagePath = imagePath;
    }

}